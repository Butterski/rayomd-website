const sampleImage = document.querySelector("[data-sample-image]");
const sampleTitle = document.querySelector("[data-sample-title]");
const sampleDetail = document.querySelector("[data-sample-detail]");
const sampleMarkdown = document.querySelector("[data-sample-markdown]");
const samplePdf = document.querySelector("[data-sample-pdf]");
const sampleCommand = document.querySelector("[data-sample-command]");

document.querySelectorAll("[data-sample]").forEach((button) => {
  button.addEventListener("click", () => {
    const sample = samples[button.dataset.sample];
    if (!sample || !sampleImage) return;
    document.querySelectorAll("[data-sample]").forEach((peer) => {
      peer.setAttribute("aria-selected", String(peer === button));
    });
    sampleImage.src = sample.image;
    sampleImage.alt = `First page of the ${sample.title} PDF generated by RayoMD`;
    sampleTitle.textContent = sample.title;
    sampleDetail.textContent = sample.detail;
    sampleMarkdown.href = sample.markdown;
    samplePdf.href = sample.pdf;
    sampleCommand.textContent = sample.command;
  });
});

const betaForm = document.querySelector("[data-beta-form]");
if (betaForm) {
  betaForm.addEventListener("submit", (event) => {
    event.preventDefault();
    const data = new FormData(betaForm);
    const workflow = data.get("workflow");
    const volume = data.get("volume");
    const timing = data.get("timing");
    const current = data.get("current") || "Not specified";
    const blocker = data.get("blocker") || "Not specified";
    const price = data.get("price") ? "Yes" : "Not yet";
    const body = [
      `### Workflow\n${workflow}`,
      `### Expected monthly volume\n${volume}`,
      `### Integration timing\n${timing}`,
      `### Current solution\n${current}`,
      `### Main requirement or blocker\n${blocker}`,
      `### Would consider the founding offer\n${price}`,
      "\n> Submitted from the RayoMD website. No confidential information included."
    ].join("\n\n");
    const issueUrl = new URL("__WEBSITE_REPO_URL__/issues/new");

    issueUrl.searchParams.set("title", `API beta: ${workflow}`);
    issueUrl.searchParams.set("body", body);
    window.location.href = issueUrl.toString();
  });
}

